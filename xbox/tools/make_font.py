# Makes src/xbox_art.h for the Xbox app's first-run screen (before the game's own fonts are there):
# a glyph sheet of printable ASCII in two sizes (Bahnschrift, white on transparent, tinted when drawn) with
# the glyph widths, and the emblem (setup/icon.png), both as PNG bytes (decoded with lodepng).
import io, os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
F = os.path.join(HERE, "..")
FONT = "C:/Windows/Fonts/bahnschrift.ttf"
SIZES = [("small", 24, "SemiBold"), ("big", 44, "Bold")]


def sheet(size, weight):
    font = ImageFont.truetype(FONT, size)
    try:
        font.set_variation_by_name(weight)
    except Exception:
        pass
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent
    widths = [int(round(font.getlength(chr(c)))) for c in range(32, 127)]
    cell_w = max(widths) + 2
    img = Image.new("RGBA", (cell_w * 16, cell_h * 6), (255, 255, 255, 0))
    d = ImageDraw.Draw(img)
    for i, c in enumerate(range(32, 127)):
        d.text(((i % 16) * cell_w + 1, (i // 16) * cell_h), chr(c), font=font, fill=(255, 255, 255, 255))
    return img, cell_w, cell_h, widths


def png_bytes(img):
    b = io.BytesIO()
    img.save(b, "PNG", optimize=True)
    return b.getvalue()


def c_array(name, data):
    lines = ["static const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % x for x in data[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


out = ["// Copyright (c) 2026 Skitzelles - part of Game Vault, https://github.com/skitzellez/xbox-game-vault",
       "// Generated by tools/make_font.py: glyph sheets (Bahnschrift) and the emblem for the Xbox first-run screen.",
       "#ifndef FALLOUT_XBOX_ART_H_", "#define FALLOUT_XBOX_ART_H_", "", "namespace fallout {", ""]
for name, size, weight in SIZES:
    img, cw, ch, widths = sheet(size, weight)
    out.append(c_array("kFont_%s_png" % name, png_bytes(img)))
    out.append("static const int kFont_%s_cell_w = %d;" % (name, cw))
    out.append("static const int kFont_%s_cell_h = %d;" % (name, ch))
    out.append("static const unsigned char kFont_%s_widths[95] = { %s };" % (name, ", ".join(map(str, widths))))
    out.append("")
emblem = Image.open(os.path.join(F, "setup", "icon.png")).convert("RGBA").resize((160, 160), Image.LANCZOS)
out.append(c_array("kEmblem_png", png_bytes(emblem)))
out += ["", "} // namespace fallout", "", "#endif /* FALLOUT_XBOX_ART_H_ */", ""]
open(os.path.join(F, "..", "src", "xbox_art.h"), "w", newline="\n").write("\n".join(out))
print("xbox_art.h written")
